"""Measure repeated solve + heterogeneous simulation + synthetic moment loss.

The target is generated by this model at leisure_weight=1, not ACS/ATUS data.
This isolates the numerical speed and stability of a calibration evaluation.
"""

from __future__ import annotations

import argparse
import json
from dataclasses import asdict
from pathlib import Path
from time import perf_counter
from typing import Any

import jax
import numpy as np
from blinder_weiss import (
    BellmanConfig,
    benchmark_params,
    cohort_moments,
    simulate_cohort,
    solve_bellman,
)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--interpolation", default="bilinear")
    parser.add_argument("--fine", action="store_true")
    parser.add_argument("--people", type=int, default=256)
    parser.add_argument("--neighbor-sweeps", type=int, default=2)
    parser.add_argument("--neighbor-tolerance", type=float, default=None)
    parser.add_argument("--neighbor-destinations", action="store_true")
    args = parser.parse_args()
    if args.people < 1:
        parser.error("--people must be positive")
    resolution = (
        dict(
            periods=140,
            asset_nodes=61,
            human_capital_nodes=49,
            hours_nodes=15,
            investment_nodes=15,
            consumption_nodes=19,
            refinement_steps=48,
        )
        if args.fine
        else {}
    )
    config = BellmanConfig(
        compute_platform="gpu",
        value_interpolation=args.interpolation,
        neighbor_policy_sweeps=args.neighbor_sweeps,
        neighbor_policy_tolerance=args.neighbor_tolerance,
        neighbor_destination_candidates=args.neighbor_destinations,
        **resolution,
    )
    rng = np.random.default_rng(125)
    assets = rng.uniform(2.0, 8.0, args.people)
    capital = np.exp(rng.uniform(-0.25, 0.25, args.people))
    weights = rng.uniform(0.5, 1.5, args.people)
    ages = np.asarray([5.0, 15.0, 25.0, 35.0, 45.0, 55.0, 65.0])
    report: dict[str, Any] = dict(
        jax=jax.__version__,
        config=asdict(config),
        people=args.people,
        seed=125,
        target="synthetic same-grid model at leisure_weight=1; no survey data",
        ages=ages.tolist(),
        results=[],
    )
    target = None
    for weight in [1.0, 0.98, 0.99, 1.01, 1.02, 1.0]:
        started = perf_counter()
        solution = solve_bellman(benchmark_params(leisure_weight=weight), config)
        solved = perf_counter()
        cohort = simulate_cohort(solution, assets, capital, weights=weights)
        moments = cohort_moments(cohort, participation_hours_threshold=0.02)
        fields = ["hours", "training_time", "earnings", "participation"]
        profiles = {key: np.interp(ages, moments.time, getattr(moments, key)) for key in fields}
        vector = np.concatenate([profiles[key] for key in fields])
        if target is None:
            target = vector.copy()
        loss = float(np.mean((vector - target) ** 2))
        row = dict(
            leisure_weight=weight,
            seconds=perf_counter() - started,
            solve_wall_seconds=solved - started,
            synthetic_loss=loss,
            moments={key: value.tolist() for key, value in profiles.items()},
            minimum_assets=float(cohort.assets.min()),
            minimum_capacity_slack=cohort.minimum_consumption_capacity_slack,
        )
        report["results"].append(row)
        report["device"] = solution.device
        args.output.parent.mkdir(parents=True, exist_ok=True)
        temp = args.output.with_suffix(".json.tmp")
        temp.write_text(json.dumps(report, indent=2) + "\n")
        temp.replace(args.output)
        print(
            json.dumps({key: value for key, value in row.items() if key != "moments"}), flush=True
        )


if __name__ == "__main__":
    main()
